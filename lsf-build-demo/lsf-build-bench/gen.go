// gen.go - generates the demo C++ project, its Makefile and build.sh
// Author: P M Shabbir Hussain
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func cmdGen(args []string) error {
	fs := flag.NewFlagSet("gen", flag.ExitOnError)
	dir := fs.String("dir", "", "project directory to create (put it on the shared NAS path)")
	files := fs.Int("files", 120, "number of C++ translation units")
	weight := fs.Int("weight", 4, "compile cost per file (template instantiations)")
	fs.Parse(args)
	if *dir == "" || *files < 1 || *weight < 1 {
		return fmt.Errorf("gen: -dir is required; -files and -weight must be >= 1")
	}
	for _, d := range []string{"include", "src"} {
		if err := os.MkdirAll(filepath.Join(*dir, d), 0o755); err != nil {
			return err
		}
	}

	var hdr, mainc strings.Builder
	hdr.WriteString("// generated by buildfarm\n#pragma once\n#include <string>\n\n")
	mainc.WriteString("// generated by buildfarm\n#include \"units.h\"\n#include <cstdio>\n\nint main() {\n" +
		"    const std::string in = \"alpha_1 beta_22 gamma_333 delta_4444\";\n    long sum = 0;\n")
	for i := 0; i < *files; i++ {
		name := fmt.Sprintf("unit_%03d", i)
		fmt.Fprintf(&hdr, "long %s(const std::string &in);\n", name)
		fmt.Fprintf(&mainc, "    sum += %s(in);\n", name)
		src := genUnit(i, *weight)
		if err := os.WriteFile(filepath.Join(*dir, "src", name+".cpp"), []byte(src), 0o644); err != nil {
			return err
		}
	}
	mainc.WriteString("    std::printf(\"build OK, checksum=%ld\\n\", sum);\n    return 0;\n}\n")

	writes := map[string]string{
		"include/units.h": hdr.String(),
		"src/main.cpp":    mainc.String(),
		"Makefile":        makefile,
		"build.sh":        buildScript,
	}
	for name, body := range writes {
		mode := os.FileMode(0o644)
		if strings.HasSuffix(name, ".sh") {
			mode = 0o755
		}
		if err := os.WriteFile(filepath.Join(*dir, name), []byte(body), mode); err != nil {
			return err
		}
	}
	fmt.Printf("generated %d C++ files (weight %d) in %s\n", *files, *weight, *dir)
	return nil
}

// genUnit emits one translation unit. Each distinct Rec_k type makes the
// compiler instantiate std::map / std::vector / std::sort again, so compile
// time grows with weight - like real-world template-heavy C++.
func genUnit(i, weight int) string {
	var b strings.Builder
	fmt.Fprintf(&b, `// generated by buildfarm
#include "units.h"
#include <algorithm>
#include <map>
#include <numeric>
#include <regex>
#include <sstream>
#include <string>
#include <vector>

#ifdef BROKEN
#if %d == 0
#error "simulated compile error (BROKEN=1)"
#endif
#endif

namespace u%03d {
`, i, i)
	for k := 0; k < weight; k++ {
		fmt.Fprintf(&b, `
struct Rec%d { std::string key; long val; double w; };

static long f%d(const std::string &in) {
    std::regex re("([a-z]+)_([0-9]+)");
    std::map<std::string, std::vector<Rec%d>> groups;
    for (std::sregex_iterator it(in.begin(), in.end(), re), end; it != end; ++it) {
        Rec%d r{(*it)[1].str(), std::stol((*it)[2].str()) + %d, %d.5};
        groups[r.key].push_back(r);
    }
    std::vector<Rec%d> all;
    for (auto &g : groups) all.insert(all.end(), g.second.begin(), g.second.end());
    std::sort(all.begin(), all.end(), [](const Rec%d &a, const Rec%d &b) { return a.val * a.w < b.val * b.w; });
    std::ostringstream os;
    for (auto &r : all) os << r.key << '=' << r.val << ';';
    return std::accumulate(all.begin(), all.end(), (long)os.str().size(),
                           [](long s, const Rec%d &r) { return s + r.val; });
}
`, k, k, k, k, i+k, k, k, k, k, k)
	}
	fmt.Fprintf(&b, "\n} // namespace u%03d\n\nlong unit_%03d(const std::string &in) {\n    long s = 0;\n", i, i)
	for k := 0; k < weight; k++ {
		fmt.Fprintf(&b, "    s += u%03d::f%d(in);\n", i, k)
	}
	b.WriteString("    return s;\n}\n")
	return b.String()
}

const makefile = `# generated by buildfarm v4 - a normal GNU Makefile: works with make and LSF lsmake
CXX      ?= g++
CXXFLAGS ?= -O2 -std=c++11
SRCS := $(sort $(wildcard src/*.cpp))
OBJS := $(patsubst src/%.cpp,obj/%.o,$(SRCS))
APP  := bin/app

all: $(APP)

$(APP): $(OBJS)
	@mkdir -p bin
	$(CXX) $(CXXFLAGS) -o $@ $(OBJS)

obj/%.o: src/%.cpp include/units.h
	@mkdir -p obj
	$(CXX) $(CXXFLAGS) -Iinclude $(if $(BROKEN),-DBROKEN) -c $< -o $@

clean:
	rm -rf obj bin

.PHONY: all clean
`

// buildScript is one developer build (an LSF job, or run over ssh): copy sources from NAS to local scratch, compile
// with as many cores as LSF allocated, publish the artifact back to NAS.
const buildScript = `#!/bin/bash
# generated by buildfarm v4 - one developer build, run as an LSF job
# usage: build.sh <src_dir_on_nas> <output_dir_on_nas> [make_jobs]
SRC=$1
OUT=$2
J=${3:-${LSB_DJOB_NUMPROC:-2}}      # under LSF: the cores allocated by bsub -n
mkdir -p "$OUT"
START=$(date +%s.%N)
WS=$(mktemp -d /tmp/build.XXXXXX)   # compile on local disk, not on NAS
cp -r "$SRC"/. "$WS"/ && cd "$WS" && make clean >/dev/null 2>&1
make -j"$J" ${BROKEN:+BROKEN=1} >"$OUT/build.log" 2>&1
RC=$?
if [ $RC -eq 0 ]; then
    tar czf "$OUT/app.tar.gz" -C "$WS" bin      # artifact -> NAS
fi
END=$(date +%s.%N)
printf '{"host":"%s","jobid":"%s","slots":%s,"start":%s,"end":%s,"rc":%d}\n' \
    "$(hostname -s)" "${LSB_JOBID:-0}" "$J" "$START" "$END" "$RC" >"$OUT/result.json.tmp"
mv "$OUT/result.json.tmp" "$OUT/result.json"
cd / && rm -rf "$WS"
exit $RC
`
